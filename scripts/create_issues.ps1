New-Issue "自律性の制限：自動常駐・遠隔操作の封印" @'
## 課題
能動的にPC操作する＝危険。自動常駐や遠隔操作は攻撃面・暴走リスクを生む。

## 判断
起動時の自動常駐と遠隔PC操作はスコープ外（封印）。危険操作（shutdown等）は実行前に確認を挟む。

## 理由
遠隔操作は外に口を開ける＝認証・通信・許可範囲の設計が重くなる。魅力的だが意図的に外す＝作らない判断の上位版。
'@

New-Issue "帰宅トリガーは「ただいま」手動発火" @'
## 課題
