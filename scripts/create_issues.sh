#!/usr/bin/env bash
# MyAgent: 設計判断 Issue を一括作成（Mac / Linux）
# 前提: gh CLI 認証済み（`gh auth login`）。リポジトリ直下で実行する。
# 使い方:  bash scripts/create_issues.sh
set -euo pipefail

gh label create "design" --color "1D76DB" --description "設計判断の記録" 2>/dev/null || true

new_issue() { echo "Creating: $1"; gh issue create --title "$1" --body "$2" --label "design"; }

new_issue "操作を「汎用ツール＋設定表」に抽象化する（引き算思想）" '## 課題
機能ごとにツールを増やすと際限なく発散する。

## 判断
汎用ツール（open_site / launch_app / run_system）＋ 名前→実体の対応表に集約。拡張は表に1行。

## 理由
TeaMyで操作を5文法に絞った引き算思想と同じ。発散を構造で防ぐ。'

new_issue "OS差分は設定ファイルに隔離する（クロスプラットフォーム）" '## 課題
WindowsとMacで起動方法・システムコマンドが違う。

## 判断
コードは共通、差分は config_win/mac.json に隔離。platform.system()で自動切替。speak.pyもsay/SAPI自動切替。

## 理由
差分をデータに追い出せばロジックは1本。口を固定すれば将来VOICEVOXに無変更で差し替え可能。'

new_issue "コンテキスト管理 vs APIコスト" '## 課題
全履歴を渡すとトークン量=コストが跳ね上がる。

## 判断
直近Nターン＋古い記憶は要約圧縮して渡す。

## 理由
TeaMy v6のコスト約1/3削減と同じ筋。賢く渡す＝安く深く。'

new_issue "画面振り分けは固定ルールでは破綻する" '## 課題
「動画は中央」固定は、勉強＋サブ動画の文脈で破綻する。

## 判断
メイン判断をLLMに委ね、表示先を動的に割り振る。

## 理由
固定スクリプトにできない判断こそLLMをかます本質的価値。'

new_issue "捏造防止：数字・予定は実データのみ" '## 課題
数字・予定をでっち上げると信頼が崩れる。

## 判断
必ず実データ（サーバー/カレンダー）から取得。知らないことは言わせない。

## 理由
TeaMyのFLAG思想と一致。執事の信頼性の土台。'

new_issue "GUIレス（作らない判断）" '## 課題
GUIを付けたくなるが、体験は発話で完結する。

## 判断
GUIを意図的に持たない。

## 理由
作らない判断＝プロダクト思考。引き算。'

new_issue "自律性の制限：自動常駐・遠隔操作の封印" '## 課題
自動常駐・遠隔操作は攻撃面・暴走リスクを生む。

## 判断
自動常駐と遠隔操作はスコープ外。危険操作は実行前に確認を挟む。

## 理由
遠隔操作は外に口を開ける＝設計が重くなる。意図的に外す＝作らない判断の上位版。'

new_issue "帰宅トリガーは「ただいま」手動発火" '## 課題
起動時自動だと勝手に喋り出して不安・うざい。

## 判断
「ただいま」での手動発火を採用。

## 理由
発火が自分の意思＝主導権を握れる。誤爆しない。(E)と(D)の合わせ技。'

new_issue "カレンダーは全取得→LLMが本人分を選別" '## 課題
実カレンダーは家族の予定と本人の予定が混在。固定ルールでは取りこぼす。

## 判断
全カレンダーを取得し、本人に関係ある予定をLLMに選別・要約させる。TODOはTasks APIから締切付きで取得。

## 理由
取得=正直に全部／取捨=LLMの動的判断。執事が予定を把握してる正体はこれ。'

new_issue "設計判断の記録方式（ADR正本＋Issue窓口）" '## 課題
設計変更を二人で承認しても、判断の経緯が会話に流れて消える。

## 判断
docs/adr/*.md を正本として git 履歴に残し、GitHub Issue を議論・可視化の窓口にミラーする。承認したものだけ記録。

## 理由
ファイルはオフラインでも履歴でも確実に残る。Issueは一覧性・議論向き。両取りで弱点を相殺。
（正本: docs/adr/0010-decision-record-method.md）'

new_issue "フレームワーク化：config 2層（auto/user）" '## 課題
配布には各自のアプリ/URLを手で書くのが重い。一方で完全自動も不可能（URL・独自コマンドは取得不可）。

## 判断
config.auto.json（スキャンで再生成）＋ config.user.json（手動・優先）に2分割し、実行時マージ。userがautoを上書き。

## 理由
自動で9割埋め、手動は最小に。再スキャンしても手動編集が消えない。配布時は「スキャン→数項目埋める」で動く。
（正本: docs/adr/0011-framework-two-layer-config.md）'

new_issue "アプリ分類・呼び名のLLM自動生成" '## 課題
スキャンで得られるのはアプリ名だけ。カテゴリも日本語の呼び名・略語も無い。

## 判断
セットアップ時にアプリ一覧をClaudeに渡し、カテゴリ＋呼び名・略語を生成してconfig.autoへ。誤りはconfig.userで上書き。

## 理由
既にClaudeを使っており追加基盤不要。任意アプリに汎用で、略語も同時に得られる。誤分類は手動層で安全に補正。
（正本: docs/adr/0012-app-classification-llm.md）'

new_issue "略語・口語の解釈（menu制約＋ファジー＋聞き返し）" '## 課題
「ばろ」「ディスコ」「ようつべ」等の略語・口語を正しい操作へ結ぶ必要がある。

## 判断
セットアップ時にLLMが呼び名リスト（略語込み）を生成しmenuに載せる（決定的）。漏れは実行時にmenu制約下でLLMが最近傍へ寄せ、不確実なら聞き返す。

## 理由
頻出語は速く確実、ロングテールはLLMで吸収。menuに閉じるので誤爆しない。
（正本: docs/adr/0013-abbreviation-handling.md）'

new_issue "言い間違い・誤認識の吸収（可逆性段階化＋エコー）" '## 課題
音声認識ミス(Step2)や本人の言い間違い・自己訂正をどう扱うか。

## 判断
可逆操作（サイト/アプリ起動）は即実行して報告、危険操作は確認。1発話内の自己訂正はLLM処理、ターンまたぎはStep5の短期記憶。不確実なら聞き返す。

## 理由
可逆操作に毎回確認するとUXが死ぬ。エコー報告で即訂正でき、確認は危険操作だけに絞れば安全と快適を両立。
（正本: docs/adr/0014-misspeak-handling.md）'

echo "完了。GitHubのIssuesタブを確認してください。"
